// Offline build-time assets. Uses the companion's existing MIT-licensed encoder.
// Run from any directory; --check verifies that the committed vectors are current.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { qrMatrix } from '../src/qr.js';

for (const [locale, folder] of [['en', 'drawable'], ['es', 'drawable-es']]) {
  const values = new URL(`../../app/src/main/res/values${locale === 'es' ? '-es' : ''}/strings.xml`, import.meta.url);
  const strings = await readFile(values, 'utf8');
  const url = strings.match(/<string name="companion_url">([^<]+)<\/string>/)?.[1];
  if (!url || new URL(url).origin !== 'https://tv-tune-kalt2212.vercel.app') throw Error('Expected public companion URL');
  const rows = qrMatrix(url), size = rows.length + 8;
  const cells = [];
  rows.forEach((row, y) => row.forEach((dark, x) => {
    if (dark) cells.push(`M${x + 4},${y + 4}h1v1h-1z`);
  }));
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by companion/test/generate-native-qr.mjs; four-module quiet zone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="180dp" android:height="180dp"
    android:viewportWidth="${size}" android:viewportHeight="${size}">
    <path android:fillColor="#FFFFFF" android:pathData="M0,0h${size}v${size}H0z" />
    <path android:fillColor="#000000" android:pathData="${cells.join('')}" />
</vector>
`;
  const directory = new URL(`../../app/src/main/res/${folder}/`, import.meta.url);
  const output = new URL('companion_qr.xml', directory);
  if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8') !== xml) throw Error(`Regenerate ${folder}/companion_qr.xml`);
  } else {
    await mkdir(directory, { recursive: true });
    await writeFile(output, xml);
  }
  console.log(`${locale}: ${url} (${rows.length} modules, four-module border)`);
}
